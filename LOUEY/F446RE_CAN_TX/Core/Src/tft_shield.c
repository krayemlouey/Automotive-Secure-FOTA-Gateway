/* Remplissage de tout l'écran avec une couleur RGB565 */
void TFT_FillScreen(uint16_t color)
{
    TFT_SetWindow(0, 0, TFT_WIDTH - 1, TFT_HEIGHT - 1);

    uint8_t hi = (uint8_t)(color >> 8);
    uint8_t lo = (uint8_t)(color & 0xFF);

    TFT_RS_HIGH();
    TFT_CS_LOW();

    uint32_t total = (uint32_t)TFT_WIDTH * TFT_HEIGHT;
    for (uint32_t i = 0; i < total; i++)
    {
        // Envoi de l'octet haut
        TFT_SetBus(hi);
        TFT_WR_LOW();
        __NOP();
        TFT_WR_HIGH();

        // Envoi de l'octet bas
        TFT_SetBus(lo);
        TFT_WR_LOW();
        __NOP();
        TFT_WR_HIGH();
    }

    TFT_CS_HIGH();
}

/* Dessin d'un pixel */
void TFT_DrawPixel(uint16_t x, uint16_t y, uint16_t color)
{
    if (x >= TFT_WIDTH || y >= TFT_HEIGHT) return;
    TFT_SetWindow(x, y, x, y);
    TFT_WriteData16(color);
}

/* Dessin d'un caractère avec multiplicateur de taille */
void TFT_DrawChar(uint16_t x, uint16_t y, char c, uint16_t color, uint16_t bg, uint8_t size)
{
    if (c < 32 || c > 126) c = ' ';
    uint8_t char_index = (uint8_t)(c - 32);

    for (uint8_t row = 0; row < 16; row++)
    {
        uint8_t line = font_8x16[char_index][row];
        for (uint8_t col = 0; col < 8; col++)
        {
            uint16_t pixel_color = (line & (0x80 >> col)) ? color : bg;

            if (size == 1)
            {
                TFT_DrawPixel(x + col, y + row, pixel_color);
            }
            else
            {
                // Agrandissement par pavés size x size
                for (uint8_t sx = 0; sx < size; sx++)
                {
                    for (uint8_t sy = 0; sy < size; sy++)
                    {
                        TFT_DrawPixel(x + col * size + sx, y + row * size + sy, pixel_color);
                    }
                }
            }
        }
    }
}

/* Affichage d'une chaîne de caractères */
void TFT_DrawString(uint16_t x, uint16_t y, const char *str, uint16_t color, uint16_t bg, uint8_t size)
{
    uint16_t cur_x = x;
    uint16_t cur_y = y;

    while (*str)
    {
        if (*str == '\n')
        {
            cur_x = x;
            cur_y += 16 * size;
        }
        else
        {
            TFT_DrawChar(cur_x, cur_y, *str, color, bg, size);
            cur_x += 8 * size;
        }
        str++;
    }
}
