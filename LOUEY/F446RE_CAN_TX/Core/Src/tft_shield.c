/* Macros de commande des broches de contrôle (actives à l'état BAS) */
#define TFT_CS_LOW()    (GPIOB->BSRR = (uint32_t)GPIO_PIN_0 << 16U)
#define TFT_CS_HIGH()   (GPIOB->BSRR = GPIO_PIN_0)

#define TFT_WR_LOW()    (GPIOC->BSRR = (uint32_t)GPIO_PIN_1 << 16U)
#define TFT_WR_HIGH()   (GPIOC->BSRR = GPIO_PIN_1)

#define TFT_RS_LOW()    (GPIOC->BSRR = (uint32_t)GPIO_PIN_0 << 16U)
#define TFT_RS_HIGH()   (GPIOC->BSRR = GPIO_PIN_0)

/*
 * Écriture d'un octet sur le bus de données 8 bits
 * Correspondance physique Arduino Uno / Shield ITEAD -> STM32 NUCLEO-F446RE :
 *  D0 -> PA3
 *  D1 -> PA2
 *  D2 -> PA10
 *  D3 -> PB3
 *  D4 -> PB5
 *  D5 -> PB4
 *  D6 -> PB10
 *  D7 -> PA8
 */
static inline void TFT_SetBus(uint8_t val)
{
    // Port A : PA2, PA3, PA8, PA10
    uint32_t pa_set = 0;
    uint32_t pa_reset = 0;

    if (val & 0x01) pa_set |= GPIO_PIN_3;   else pa_reset |= GPIO_PIN_3;   // D0 -> PA3
    if (val & 0x02) pa_set |= GPIO_PIN_2;   else pa_reset |= GPIO_PIN_2;   // D1 -> PA2
    if (val & 0x04) pa_set |= GPIO_PIN_10;  else pa_reset |= GPIO_PIN_10;  // D2 -> PA10
    if (val & 0x80) pa_set |= GPIO_PIN_8;   else pa_reset |= GPIO_PIN_8;   // D7 -> PA8

    GPIOA->BSRR = pa_set | (pa_reset << 16U);

    // Port B : PB3, PB4, PB5, PB10
    uint32_t pb_set = 0;
    uint32_t pb_reset = 0;

    if (val & 0x08) pb_set |= GPIO_PIN_3;   else pb_reset |= GPIO_PIN_3;   // D3 -> PB3
    if (val & 0x10) pb_set |= GPIO_PIN_5;   else pb_reset |= GPIO_PIN_5;   // D4 -> PB5
    if (val & 0x20) pb_set |= GPIO_PIN_4;   else pb_reset |= GPIO_PIN_4;   // D5 -> PB4
    if (val & 0x40) pb_set |= GPIO_PIN_10;  else pb_reset |= GPIO_PIN_10;  // D6 -> PB10

    GPIOB->BSRR = pb_set | (pb_reset << 16U);
}

/* Envoi d'une commande (RS = 0) */
void TFT_WriteCmd(uint8_t cmd)
{
    TFT_RS_LOW();
    TFT_CS_LOW();
    TFT_SetBus(cmd);
    TFT_WR_LOW();
    __NOP();
    TFT_WR_HIGH();
    TFT_CS_HIGH();
}

/* Envoi d'une donnée (RS = 1) */
void TFT_WriteData(uint8_t data)
{
    TFT_RS_HIGH();
    TFT_CS_LOW();
    TFT_SetBus(data);
    TFT_WR_LOW();
    __NOP();
    TFT_WR_HIGH();
    TFT_CS_HIGH();
}

/* Envoi de 16 bits de données */
void TFT_WriteData16(uint16_t data)
{
    TFT_WriteData((uint8_t)(data >> 8));
    TFT_WriteData((uint8_t)(data & 0xFF));
}

#if defined(TFT_CONTROLLER_S6D1121)
static void S6D1121_WriteReg(uint8_t reg, uint16_t val)
{
    TFT_WriteCmd(reg);
    TFT_WriteData16(val);
}
#endif

